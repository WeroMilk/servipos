/** Slots disponibles para asignar ubicación física a un producto. */
export const MUEBLE_SLOTS: readonly string[] = [...SLOT_ORDER];

/** Letras/slots de mueble para conteo: Mostrador, BANDAS, A–Ñ–Z y AA…PP. */
export const MUEBLE_LETRAS: readonly string[] = (() => {
  const singles = [
    ...Array.from({ length: 14 }, (_, i) => String.fromCharCode(65 + i)), // A–N
    'Ñ',
    ...Array.from({ length: 12 }, (_, i) => String.fromCharCode(79 + i)), // O–Z
  ];
  // AA…NN, ÑÑ, OO…PP (croquis muro / islas dobles)
  const doubles = [
    ...Array.from({ length: 14 }, (_, i) => {
      const ch = String.fromCharCode(65 + i); // A…N
      return `${ch}${ch}`;
    }),
    'ÑÑ',
    ...Array.from({ length: 2 }, (_, i) => {
      const ch = String.fromCharCode(79 + i); // O…P
      return `${ch}${ch}`;
    }),
  ];
  return ['Mostrador', 'BANDAS', 'Cajonera', 'Bodega', ...singles, ...doubles];
})();

/** ¿El slot (A3, AA, PP1…) pertenece al mueble elegido (A, AA, PP…)? */
export function slotPerteneceAMueble(slot: string, muebleLetra: string): boolean {
  const s = (slot ?? '').trim().toUpperCase();
  const L = (muebleLetra ?? '').trim().toUpperCase();
  if (!s || !L) return false;
  if (s === L) return true;
  // Evita que "AA" cuente como mueble "A"
  return new RegExp(`^${L}\\d+$`).test(s);
}

/** Código normalizado → slots (sin duplicar el mismo slot). */
const CODIGO_A_UBICACIONES: ReadonlyMap<string, readonly string[]> = (() => {
  const map = new Map<string, string[]>();
  for (const slot of SLOT_ORDER) {
    const codes = MUEBLE_POR_SLOT[slot] ?? [];
    for (const raw of codes) {
      const key = normSkuBarcode(raw);
      if (!key) continue;
      const existing = map.get(key);
      if (!existing) {
        map.set(key, [slot]);
      } else if (!existing.includes(slot)) {
        existing.push(slot);
      }
    }
  }
  return map;
})();

/**
 * Une slots sin duplicar y respeta el orden de SLOT_ORDER.
 */
function mergeSlotsOrdered(...lists: Array<readonly string[] | undefined>): string[] {
  const seen = new Set<string>();
  for (const list of lists) {
    if (!list) continue;
    for (const slot of list) {
      const s = (slot ?? '').trim();
      if (s) seen.add(s);
    }
  }
  if (seen.size === 0) return [];
  const ordered: string[] = [];
  for (const slot of SLOT_ORDER) {
    if (seen.has(slot)) {
      ordered.push(slot);
      seen.delete(slot);
    }
  }
  // Cualquier slot fuera del orden conocido (p. ej. tipográfico)
  for (const slot of seen) ordered.push(slot);
  return ordered;
}

/**
 * Ubicaciones físicas por SKU y/o código de barras (mapa estático; puede devolver varios estantes).
 */
export function getUbicacionesProducto(sku: string, codigoBarras?: string | null): string[] {
  const bySku = CODIGO_A_UBICACIONES.get(normSkuBarcode(sku));
  const barcode = (codigoBarras ?? '').trim();
  const byBarcode = barcode ? CODIGO_A_UBICACIONES.get(normSkuBarcode(barcode)) : undefined;
  return mergeSlotsOrdered(bySku, byBarcode);
}

/**
 * Ubicaciones efectivas.
 * Si el producto tiene `ubicacionFisica` guardada, esa es la única (reemplaza el mapa).
 * Así un traslado Q1→U2 deja de mostrar ambos estantes.
 * Sin campo guardado, se usan las del mapa estático (puede haber varios).
 */
export function resolveUbicacionesProducto(product: {
  sku: string;
  codigoBarras?: string | null;
  ubicacionFisica?: string | null;
}): string[] {
  const saved = (product.ubicacionFisica ?? '').trim();
  if (saved) return [saved];
  return getUbicacionesProducto(product.sku, product.codigoBarras);
}

export function productoPerteneceAMueble(
  product: {
    sku: string;
    codigoBarras?: string | null;
    ubicacionFisica?: string | null;
  },
  muebleLetra: string
): boolean {
  return resolveUbicacionesProducto(product).some((slot) => slotPerteneceAMueble(slot, muebleLetra));
}
